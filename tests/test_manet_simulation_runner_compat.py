def test_custom_scenario_with_ids_enabled_compatibility(tmp_path: Path) -> None:
    """Verify IDS-enabled custom configuration compatibility and model gating behavior."""
    model_file = Path.cwd() / "ml" / "models" / "best_model.joblib"

    if model_file.is_file() and model_file.stat().st_size > 0:
        # Champion model is present: build configuration with ids_enabled=True
        ids_cfg = CustomScenarioBuilder.build(
            nodes=10,
            duration=3.0,
            seed=42,
            attack_type="Blackhole",
            ids_enabled=True,
            advanced_params={"rate_pps": 2.0},
        )
        errors = validate_structural_invariants(ids_cfg, model_path=model_file)
        assert errors == [], f"Expected zero errors when model artifact is present: {errors}"

        trace_file = tmp_path / "ids_trace.csv"
        runner = SimulationRunner(
            scenario_config=ids_cfg,
            seed=42,
            out_path=trace_file,
        )
        assert runner.online_ids is not None
        metrics = runner.run(duration=3.0)
        assert isinstance(metrics, dict)
        assert trace_file.is_file()
    else:
        # If model is absent, verify structural invariant rejects ids_enabled=True
        ids_cfg = CustomScenarioBuilder.build(
            nodes=10,
            duration=3.0,
            seed=42,
            attack_type="Blackhole",
            ids_enabled=True,
        )
        errors = validate_structural_invariants(ids_cfg, model_path=Path("nonexistent_model.joblib"))
        assert len(errors) == 1
        assert "champion model artifact" in errors[0]
