"""End-to-end integration tests verifying SimulationRunner compatibility with TUI scenario configurations.

Verifies:
- Authentic preset scenario schemas loaded via ScenarioAdapter are directly consumable by SimulationRunner.
- Custom scenario configurations generated via CustomScenarioBuilder execute deterministically in SimulationRunner.
- Generated traces strictly conform to SimulationRunner.TRACE_HEADER schema.
- Workspace experiment directory allocation and launch manifest records accurately reflect run configurations.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

import pytest

from manet.adapters.scenario import ScenarioAdapter
from manet.adapters.simulation_config import (
    CustomScenarioBuilder,
    validate_structural_invariants,
)
from manet.adapters.workspace import WorkspaceAdapter, record_launch_manifest
from simulator.run_scenario import SimulationRunner


def test_preset_scenarios_compatibility_with_simulation_runner(tmp_path: Path) -> None:
    """Verify authentic preset scenarios discovered by ScenarioAdapter run cleanly in SimulationRunner."""
    adapter = ScenarioAdapter()
    presets = adapter.list_presets()
    assert len(presets) >= 4, f"Expected at least 4 preset scenarios in scenarios/, found {len(presets)}"

    # Select the first authentic baseline preset (e.g. e1_normal_30n)
    preset = presets[0]
    assert preset.raw_config is not None
    assert isinstance(preset.raw_config, dict)

    # Invariant validation must pass cleanly
    errors = validate_structural_invariants(preset.raw_config)
    assert errors == [], f"Preset {preset.scenario_id} failed structural validation: {errors}"

    # Create a fast test configuration (2.0s duration per T-09-09)
    test_config: dict[str, Any] = dict(preset.raw_config)
    test_config["duration"] = 2.0

    trace_file = tmp_path / "preset_trace.csv"
    runner = SimulationRunner(
        scenario_config=test_config,
        seed=42,
        out_path=trace_file,
    )

    metrics = runner.run(duration=2.0)
    assert isinstance(metrics, dict)
    assert "pdr" in metrics
    assert "throughput_bps" in metrics
    assert "avg_delay_s" in metrics
    assert "packet_loss_ratio" in metrics

    # Verify trace file exists and matches canonical schema
    assert trace_file.is_file()
    with open(trace_file, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        assert header == SimulationRunner.TRACE_HEADER
        rows = list(reader)
        assert len(rows) > 0, "Expected non-empty trace log from simulation run"


def test_custom_scenario_builder_compatibility_with_simulation_runner(tmp_path: Path) -> None:
    """Verify custom configurations generated by CustomScenarioBuilder execute in SimulationRunner."""
    custom_cfg = CustomScenarioBuilder.build(
        nodes=10,
        duration=5.0,
        seed=42,
        attack_type="Blackhole",
        ids_enabled=False,
        advanced_params={
            "radio_range": 300.0,
            "loss_probability": 0.0,
            "rate_pps": 2.0,
            "seq_offset": 500,
            "spoofed_hops": 1,
        },
    )

    # Invariant validation
    errors = validate_structural_invariants(custom_cfg)
    assert errors == [], f"Custom configuration failed invariant validation: {errors}"

    # Allocate workspace directory and record initial launch manifest
    ws_adapter = WorkspaceAdapter(workspace_root=tmp_path)
    exp_id, exp_dir = ws_adapter.allocate_experiment_directory(
        scenario_name="custom_10n_blackhole",
        seed=42,
        tag="compat_test",
    )
    assert exp_dir.is_dir()

    manifest_path = record_launch_manifest(
        experiment_dir=exp_dir,
        experiment_id=exp_id,
        scenario_name="custom_10n_blackhole",
        seed=42,
        config=custom_cfg,
    )
    assert manifest_path.is_file()

    # Verify manifest content
    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest_data = json.load(f)
    assert manifest_data["experiment_id"] == exp_id
    assert manifest_data["scenario_name"] == "custom_10n_blackhole"
    assert manifest_data["seed"] == 42
    assert manifest_data["status"] == "CONFIGURED"
    assert manifest_data["configuration"] == custom_cfg

    # Execute simulation in the allocated directory
    trace_path = exp_dir / "trace.csv"
    runner = SimulationRunner(
        scenario_config=custom_cfg,
        seed=42,
        out_path=trace_path,
    )
    metrics = runner.run(duration=5.0)

    assert isinstance(metrics, dict)
    assert trace_path.is_file()

    # Validate canonical trace header and data rows
    with open(trace_path, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader)
        assert header == SimulationRunner.TRACE_HEADER
        rows = list(reader)
        assert len(rows) > 0


